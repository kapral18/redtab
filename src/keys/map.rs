pub struct Binding {
    pub keys: &'static str,
    pub action: Action,
    pub description: &'static str,
}

macro_rules! binding {
    ($keys:literal, $action:ident, $description:literal) => {
        Binding {
            keys: $keys,
            action: Action::$action,
            description: $description,
        }
    };
}

